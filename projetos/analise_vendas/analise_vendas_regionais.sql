-- Análise de vendas por região
-- Analise de vendas, custos e mecanicas promocionais (exemplo anonimizado).
-- Identificadores genericos devem ser adaptados aos valores reais do ambiente de execucao.
-- A origem de BASECMV nao constava no SQL fornecido.

WITH BASECMV AS (SELECT 
CONCAT('marca', SKU) AS SKU,
CMV AS COGS 
FROM /* TODO: informar a tabela de origem do CMV */ 
WHERE MARCA = ''),

BASEVENDAS AS (SELECT  
MARCA, 
DT_CAPTADA,
-- CONCAT('SEM ', EXTRACT(WEEK FROM DT_CAPTADA)) AS SEMANA,
date_format(DT_CAPTADA, 'EEE') AS D_SEM,
HORA,
CD_PEDIDO,
SUBSTR(DT_CAPTADA, 1, 7) AS ANOMES,
EXTRACT(YEAR FROM DT_CAPTADA) AS YEAR,
CASE 
WHEN DT_CAPTADA BETWEEN '2024-08-09' AND '2024-08-15'THEN 'YTD2023'
WHEN DT_CAPTADA BETWEEN '2024-08-16' AND '2024-08-22'THEN 'YTD2024'
ELSE CONCAT(SUBSTRING(DT_CAPTADA,1,7),' | SEM ', DATEPART('week', DT_CAPTADA)) 
END AS PERIODO,
DC_SITUACAOPAGAMENTO,
DC_STATUSPEDIDO,
ORD.DC_MEIOPAGAMENTO,
DC_METODO_ENVIO,
MODELO_COMERCIAL,
DEVICE,
UF_ENDENTR,
CASE
WHEN ORD.UF_ENDENTR IN ('AC', 'AP', 'AM', 'PA', 'RO', 'RR', 'TO') THEN 'Norte'
WHEN ORD.UF_ENDENTR IN ('AL', 'BA', 'CE', 'MA', 'PB', 'PE', 'PI', 'RN', 'SE') THEN 'Nordeste'
WHEN ORD.UF_ENDENTR IN ('GO', 'MT', 'MS', 'DF') THEN 'Centro-Oeste'
WHEN ORD.UF_ENDENTR IN ('ES', 'MG', 'RJ', 'SP') THEN 'Sudeste'
WHEN ORD.UF_ENDENTR IN ('PR', 'RS', 'SC') THEN 'Sul'
ELSE 'Outros'
END AS REGIAO_ENTREGA,
CASE WHEN CD_VENDA_KIT IS NULL OR CD_VENDA_KIT = '' THEN CD_VENDA_ITEM ELSE CD_VENDA_KIT END AS SKU_KIT,
CASE WHEN CD_VENDA_KIT IS NULL OR CD_VENDA_KIT = '' THEN DC_VENDA_ITEM ELSE DC_VENDA_KIT END AS ITEM_KIT,
– CD_VENDA_ITEM,
– CD_VENDA_KIT,
– DC_VENDA_ITEM,
– DC_VENDA_KIT,
– ID_CUPOM,
TIPO_CUPOM,
CASE WHEN ORD.DC_CATEGORIA = 'NAO_INFORMADO' THEN MEC.CATEGORIA_FINANCEIRA ELSE ORD.DC_CATEGORIA END AS CATEGORIA_FINANCEIRA_MEC,
    CASE 
      WHEN MEC.DT_INI < '2024-07-26' THEN 
        CASE
          WHEN MEC.TIPO = '-' AND MEC.DESCONTO > 0 THEN 'Outros'
          WHEN MEC.TIPO = '-' AND MEC.DESCONTO = 0 THEN 'Outros'
          WHEN MEC.TIPO = 'DE POR CICLO' AND MEC.DESCONTO = 0 THEN 'De-Por (Ciclo)'
          WHEN MEC.TIPO = 'DE POR CICLO' AND MEC.DESCONTO > 0 THEN 'De-Por (Ciclo)'
          WHEN MEC.TIPO = 'DE POR EXCLUSIVO' AND MEC.DESCONTO > 0 AND MEC.OBS IS NULL THEN 'De-Por (Exclusivo Online)'
          WHEN MEC.TIPO = 'DE POR EXCLUSIVO' AND MEC.DESCONTO > 0 AND MEC.OBS IS NOT NULL THEN 'De-Por (Exclusivo Online Efemerides)'
          WHEN MEC.TIPO = 'DE POR EXCLUSIVO' AND MEC.DESCONTO = 0 THEN 'De-Por (Exclusivo Online Efemerides)'
          WHEN MEC.TIPO = 'DE POR OMNI' AND MEC.DESCONTO > 0 THEN 'De-Por (Ciclo)'
          WHEN MEC.TIPO = 'DE POR RI' AND MEC.DESCONTO = 0 THEN 'Mecanica RI (Ciclo)'
          WHEN MEC.TIPO = 'DE POR RI' AND MEC.DESCONTO > 0 THEN 'Mecanica RI (Ciclo)'
          WHEN MEC.TIPO = 'EXCLUSIVO ONLINE' AND MEC.DESCONTO > 0 AND MEC.OBS IS NULL THEN 'De-Por (Exclusivo Online)'
          WHEN MEC.TIPO = 'EXCLUSIVO ONLINE' AND MEC.DESCONTO > 0 AND MEC.OBS IS NOT NULL THEN 'De-Por (Exclusivo Online Efemerides)'
          WHEN MEC.TIPO = 'EXCLUSIVO ONLINE' AND MEC.DESCONTO = 0 THEN 'De-Por (Exclusivo Online Efemerides)'
          WHEN MEC.TIPO = 'FORA' AND MEC.DESCONTO = 0 THEN 'Outros'
          WHEN MEC.TIPO = 'FORA DA GRADE' AND MEC.DESCONTO > 0 THEN 'Outros'
          WHEN MEC.TIPO = 'FORA DA GRADE' AND MEC.DESCONTO = 0 THEN 'Outros'
          WHEN MEC.TIPO = 'KIT E COMBOS' AND MEC.DESCONTO > 0 THEN 'De-Por (Kit)'
          WHEN MEC.TIPO = 'KIT E COMBOS' AND MEC.DESCONTO = 0 THEN 'VNP (Ciclo)'
          WHEN MEC.TIPO = 'KITS E COMBOS' AND MEC.DESCONTO > 0 THEN 'De-Por (Kit)'
          WHEN MEC.TIPO = 'KITS E COMBOS' AND MEC.DESCONTO = 0 THEN 'VNP (Ciclo)'
          WHEN MEC.TIPO = 'MONTE SEU PRESENTE' AND MEC.DESCONTO > 0 THEN 'De-Por (Presentes)'
          WHEN MEC.TIPO = 'MONTE SEU PRESENTE' AND MEC.DESCONTO = 0 THEN 'VNP (Presentes)'
          WHEN MEC.TIPO = 'FRIDAY' AND MEC.DESCONTO > 0 THEN 'De-Por (Ciclo - Friday)'
          WHEN MEC.TIPO = 'OUTROS' AND MEC.DESCONTO > 0 THEN 'Outros'
          WHEN MEC.TIPO = 'OUTROS' AND MEC.DESCONTO = 0 THEN 'Outros'
          WHEN MEC.TIPO = 'PLANO B' AND MEC.DESCONTO > 0 THEN 'Outros'
          WHEN MEC.TIPO = 'PLANO B' AND MEC.DESCONTO = 0 THEN 'Outros'
          WHEN MEC.TIPO = 'PRESENTES' AND MEC.DESCONTO = 0 THEN 'VNP (Presentes)'
          WHEN MEC.TIPO = 'PRESENTES' AND MEC.DESCONTO > 0 THEN 'De-Por (Presentes)'
          WHEN MEC.TIPO = 'PROGRESSIVO' AND MEC.DESCONTO = 0 THEN 'Progressivo'
          WHEN MEC.TIPO = 'PROGRESSIVO' AND MEC.DESCONTO > 0 THEN 'Progressivo'
          WHEN MEC.TIPO = 'REMANESCENTE' AND MEC.DESCONTO = 0 THEN 'Remanescente'
          WHEN MEC.TIPO = 'REMANESCENTE' AND MEC.DESCONTO > 0 THEN 'Remanescente'
          WHEN MEC.TIPO = 'REMANESCENTES' AND MEC.DESCONTO > 0 THEN 'Remanescente'
          WHEN MEC.TIPO = 'REMANESCENTES' AND MEC.DESCONTO = 0 THEN 'Remanescente'
          WHEN MEC.TIPO = 'RI FRIDAY' AND MEC.DESCONTO > 0 THEN 'Mecanica RI (Relampago - Friday)'
          WHEN MEC.TIPO = 'RI RELÃ‚MPAGO' AND MEC.DESCONTO = 0 THEN 'Mecanica RI (Relampago)'
          WHEN MEC.TIPO = 'RI RELÃ‚MPAGO' AND MEC.DESCONTO > 0 THEN 'Mecanica RI (Relampago)'
          WHEN MEC.TIPO = 'RI RELAMPAGO' AND MEC.DESCONTO > 0 THEN 'Mecanica RI (Relampago)'
          WHEN MEC.TIPO = 'RI RELÂMPAGO' AND MEC.DESCONTO > 0 THEN 'Mecanica RI (Relampago)'
          WHEN MEC.TIPO = 'VNP' AND MEC.DESCONTO = 0 THEN 'VNP (Ciclo)'
          WHEN MEC.TIPO = 'VNP' AND MEC.DESCONTO > 0 THEN 'VNP (Ciclo)'
          ELSE 'Outros'
        END
      ELSE
        CASE 
          WHEN MEC.TIPO = 'DE-POR CICLO' THEN 'De-Por (Ciclo)'
          WHEN MEC.TIPO = 'DE-POR EXCLUSIVO EFEMERIDES' THEN 'De-Por (Exclusivo Online Efemerides)'
          WHEN MEC.TIPO = 'DE-POR EXCLUSIVO ONLINE' THEN 'De-Por (Exclusivo Online)'
          WHEN MEC.TIPO = 'DE-POR KIT''S' THEN 'De-Por (Kit)'
          WHEN MEC.TIPO = "DE-POR KIT'S" THEN 'De-Por (Kit)'
          WHEN MEC.TIPO = 'DE-POR PRESENTES' THEN 'De-Por (Presentes)'
          WHEN MEC.TIPO = 'DE-POR (PRESENTES)' THEN 'De-Por (Presentes)'
          WHEN MEC.TIPO = 'DE-POR RI (CICLO)' THEN 'Mecanica RI (Ciclo)'
          WHEN MEC.TIPO = 'DE-POR RI (RELAMPAGO)' THEN 'Mecanica RI (Relampago)'
          WHEN MEC.TIPO = 'PROGRESSIVO' THEN 'Progressivo'
          WHEN MEC.TIPO = 'REMANESCENTE' THEN 'Remanescente'
          WHEN MEC.TIPO = 'VNP' THEN 'VNP (Ciclo)'
          WHEN MEC.TIPO = 'VNP - EXCLUSIVO ONLINE' THEN 'VNP (Ciclo)'
          WHEN MEC.TIPO = 'VNP (KITS)' THEN 'VNP (Ciclo)'
          WHEN MEC.TIPO = 'VNP (PRESENTES)' THEN 'VNP (Presentes)'
          WHEN MEC.TIPO = 'DE-POR EXCLUSIVO SOBRAS' THEN 'De-Por (Exclusivo Online Sobras)'
          WHEN MEC.TIPO = 'DE-POR EXCLUSIVO KIT' THEN 'De-Por (Exclusivo Online Kit)'
          WHEN MEC.TIPO = 'PROGRESSIVO LINHA_PRODUTO' THEN 'Progressivo Linha Produto'
          ELSE 'Outros'
        END
    END AS TIPO_NOVO,
-- MEC.CURVA_ABC, 
-- FL_KIT
-- COUNT(DISTINCT PERSON_NUMBER_CB) AS PERSON_NUMBER_CB,
-- COUNT(DISTINCT CD_PEDIDO) AS PEDIDOS, 
ROUND(SUM(RBTB_TT),2) AS RBTB_TT, -- valor teórico
ROUND(SUM(RBCFL),2) AS RBCFL, -- valor pago cf
ROUND(SUM(RB),2) AS RB,
ROUND(SUM(RB_FRETE),2) AS RB_FRETE,
-- ROUND(SUM(RBCFL+VLR_FRETE_PAGO),2) AS GMV,
ROUND(SUM(VLR_FRETE_PAGO),2) AS FRETE,
ROUND(SUM(QT_ITENS),2) AS ITENS,
CG.COGS,
ROUND(SUM(QT_ITENS)*CG.COGS,2) AS CMV_TT_AJUSTADO
-- ROUND(SUM(COMISSAO_CB),2) AS COMISSAO_CB

FROM sandbox.canal_online.kd_full_commerce_online AS ORD 

LEFT JOIN sandbox.canal_online.tb_grade_de_mecanicas AS MEC
ON ORD.DT_CAPTADA BETWEEN MEC.DT_INI AND MEC.DT_FIM
AND REPLACE(CASE WHEN ORD.CD_VENDA_KIT IS NULL OR ORD.CD_VENDA_KIT = '' THEN ORD.CD_VENDA_ITEM ELSE ORD.CD_VENDA_KIT END,'MARCA-','') = CAST(MEC.SKU AS STRING)

LEFT JOIN BASECMV AS CG
ON ORD.CD_VENDA_ITEM = CG.SKU
WHERE MARCA = ''
  AND DC_SITUACAOPAGAMENTO = 'PAGO'
  AND DT_CAPTADA BETWEEN '2025-02-01' AND '2025-03-05'
  -- AND DT_CAPTADA = '2025-02-11' 
  -- AND MODELO_COMERCIAL = ''
  -- AND (LOWER(DC_VENDA_ITEM) LIKE '%linha_produto%')
GROUP BY ALL
)

SELECT 
DT_CAPTADA,
SEMANA,
D_SEM,
DC_SITUACAOPAGAMENTO,
MODELO_COMERCIAL,
TIPO_CUPOM,
CASE 
    WHEN CATEGORIA_FINANCEIRA_MEC = 'BARBA' THEN 'BARBA'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'ROSTO' THEN 'ROSTO'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'CABELO' THEN 'CABELO'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'DESODORANTE' THEN 'DESODORANTE'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'ÓLEO' THEN 'OLEO'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'SABONETE' THEN 'SABONETE'
    WHEN CATEGORIA_FINANCEIRA_MEC IN ('Não Atribuído', 'NAO_INFORMADO') THEN 'NAO_INFORMADO'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'MAQUIAGEM' THEN 'MAQUIAGEM'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'PERFUMARIA' THEN 'PERFUMARIA'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'CORPO' THEN 'CORPO'
    WHEN CATEGORIA_FINANCEIRA_MEC = 'PROTEÇÃO SOLAR' THEN 'PROTECAO_SOLAR'
    WHEN CATEGORIA_FINANCEIRA_MEC IS NULL OR CATEGORIA_FINANCEIRA_MEC IN ('SIGLA_PROJETO', 'OUTROS', 'PROJETO_SOCIAL', 'INFANTIL', 'PRESENTES') THEN 'OUTROS'
    ELSE 'OUTROS'
END AS FL_CATEGORIA_FINANCEIRA, 
TIPO_NOVO,
CASE
        WHEN TIPO_NOVO IN ('VNP (Presentes)', 'VNP (Ciclo)') THEN 'VNP'
        WHEN TIPO_NOVO IN ('Mecanica RI (Ciclo)', 'Mecanica RI (Relampago - Friday)', 'Mecanica RI (Relampago)') THEN 'Mecanicas RI'
        WHEN TIPO_NOVO IN ('De-Por (Ciclo)', 'De-Por (Kit)', 'De-Por (Ciclo - Friday)', 'De-Por (Exclusivo Online Kit)', 'De-Por (Exclusivo Online Sobras)') THEN 'De-Por Ciclo'
        WHEN TIPO_NOVO = 'Remanescente' THEN 'Remanescente'
        WHEN TIPO_NOVO = 'Progressivo' THEN 'Progressivo'
        WHEN TIPO_NOVO = 'De-Por (Exclusivo Online Efemerides)' THEN 'Efemerides'
        WHEN TIPO_NOVO = 'De-Por (Exclusivo Online)' THEN 'Itens Virtuais'
        WHEN TIPO_NOVO = 'De-Por (Presentes)' THEN 'Presentes'
        WHEN TIPO_NOVO = 'Progressivo Linha Produto' THEN 'Progressivo Linha Produto'
        ELSE 'Outros'
    END AS FL_TIPO_NOVO,
ROUND(SUM(RBTB_TT),2) AS RBTB_TT, -- valor teórico
ROUND(SUM(RBCFL),2) AS RBCFL, -- valor pago cf
ROUND(SUM(RB),2) AS RB,
ROUND(SUM(RB_FRETE),2) AS RB_FRETE,
ROUND(SUM(RBCFL+FRETE),2) AS GMV,
ROUND(SUM(FRETE),2) AS FRETE,
ROUND(SUM(ITENS),2) AS ITENS,
-- COGS,
ROUND(SUM(CMV_TT_AJUSTADO),2) AS CMV_TT_AJUSTADO,
ROUND((SUM(RB)*0.821),2) AS RL_PRODUTO,  
ROUND(SUM(RB)-SUM(CMV_TT_AJUSTADO)-SUM(RB*0.179),2) AS MB_PRODUTO,
ROUND(ROUND(SUM(RB)-SUM(CMV_TT_AJUSTADO)-SUM(RB*0.179),2)/ROUND((SUM(RB)*0.821),2),4) AS MB
FROM BASEVENDAS
GROUP BY ALL
