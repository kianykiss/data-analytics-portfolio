WITH MASTERPEDIDO AS (
  SELECT
    DISTINCT CD_PEDIDO,
    RETORNO_CF_PEDIDO
  FROM
    product.master_pedido_pessoa.master_pedido
  WHERE
    PAIS = 'BRASIL'
    AND MARCA = 'marca'
    AND CANAL = 'ONLINE'
    AND DT_CAPTADA BETWEEN '2024-03-01'AND '2024-09-20'
),
BASEPEDIDOS AS (
  SELECT
    DISTINCT ORD.DT_CAPTADA,
    SUBSTR(ORD.DT_CAPTADA, 1, 7) AS ANOMES,
    CONCAT('SEM ',EXTRACT(WEEK FROM ORD.DT_CAPTADA)) AS SEMANA,
    M.RETORNO_CF_PEDIDO,
    DC_SITUACAOPAGAMENTO,
    DC_MEIOPAGAMENTO,
    MODELO_COMERCIAL,
    DEVICE,
    ID_CUPOM,
    TIPO_CUPOM,
    ORD.CD_PEDIDO,
    CASE
      WHEN ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) <= 50 THEN 'Até R$ 50'
      WHEN ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) > 50
      AND ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) <= 100 THEN 'Entre R$ 50.01 e R$ 100'
      WHEN ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) > 100
      AND ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) <= 150 THEN 'Entre R$ 100.01 e R$ 150'
      WHEN ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) > 150
      AND ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) <= 200 THEN 'Entre R$ 150.01 e R$ 200'
      WHEN ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) > 200
      AND ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) <= 300 THEN 'Entre R$ 200.01 e R$ 300'
      WHEN ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) > 300
      AND ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) <= 400 THEN 'Entre R$ 300.01 e R$ 400'
      ELSE 'Acima de R$ 400'
    END AS AOV_GMV_RANGE,
    CASE
      WHEN SUM(VLR_FRETE_PAGO) IS NULL THEN 'Frete não informado'
      WHEN SUM(VLR_FRETE_PAGO) = 0 THEN 'Frete não pago'
      WHEN SUM(VLR_FRETE_PAGO) > 0 THEN 'Frete pago'
      ELSE 'Valor inválido' -- opcional, caso precise tratar outros valores
    END AS status_frete,
    DC_METODO_ENVIO,
    ROUND(SUM(QT_ITENS), 2) AS ITENS,
    ROUND(SUM(VLR_FRETE_PAGO), 2) AS FRETE,
    ROUND(SUM(RBCFL + VLR_FRETE_PAGO), 2) AS RBCFL_FRETE,
    ROUND(SUM(RB_FRETE), 2) AS RB_FRETE
  FROM
    AS ORD
    LEFT JOIN MASTERPEDIDO AS M ON ORD.CD_PEDIDO = M.CD_PEDIDO
  WHERE
    MARCA = 'marca'
    AND DC_SITUACAOPAGAMENTO = 'PAGO'
    AND DT_CAPTADA BETWEEN '2024-03-01'
    AND '2024-09-20'
  GROUP BY
    ALL
)
SELECT
  ANOMES,
  DC_SITUACAOPAGAMENTO,
  RETORNO_CF_PEDIDO,
  DEVICE,
  MODELO_COMERCIAL,
  ID_CUPOM,
  TIPO_CUPOM,
  AOV_GMV_RANGE,
  DC_METODO_ENVIO,
  COUNT(DISTINCT CD_PEDIDO) AS PEDIDOS,
  ROUND(SUM(ITENS), 2) AS ITENS,
  ROUND(SUM(RBCFL_FRETE), 2) AS RBCFL_FRETE,
  ROUND(SUM(RB_FRETE), 2) AS RB_FRETE
FROM 
  BASEPEDIDOS
GROUP BY
  ANOMES,
  MODELO_COMERCIAL,
  AOV_GMV_RANGE,
  DC_SITUACAOPAGAMENTO,
  DEVICE,
  ID_CUPOM,
  TIPO_CUPOM,
  DC_METODO_ENVIO,
  RETORNO_CF_PEDIDO


