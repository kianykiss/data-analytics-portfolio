WITH BASE_CPF_MELI AS (
    SELECT DISTINCT
        CASE
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) > 11 THEN TRIM(CAST(CPF AS STRING))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 11 THEN TRIM(CAST(CPF AS STRING))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 10 THEN CONCAT('0', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 9  THEN CONCAT('00', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 8  THEN CONCAT('000', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 7  THEN CONCAT('0000', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 6  THEN CONCAT('00000', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 5  THEN CONCAT('000000', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 4  THEN CONCAT('0000000', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 3  THEN CONCAT('00000000', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 2  THEN CONCAT('000000000', TRIM(CAST(CPF AS STRING)))
            WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 1  THEN CONCAT('0000000000', TRIM(CAST(CPF AS STRING)))
            ELSE NULL
        END AS CPF_MELI
    FROM sandbox.canal_online.tb_mktplace_meli_realizado -- BASE MANUAL EXPORTADA PELO MELI COM 35869 CPFS
    WHERE MARCA = 'Natura'
      AND CPF IS NOT NULL
),

BASE_MASTER AS (
    SELECT DISTINCT
        MODELO_COMERCIAL,
        LPAD(a.CPF, 11, '0') AS CPF_MASTER,
        CPF_MELI,
        CASE
            WHEN LPAD(a.CPF, 11, '0') = b.CPF_MELI THEN 'CPF igual ao CPF_MELI'
            WHEN LPAD(a.CPF, 11, '0') != b.CPF_MELI THEN 'CPF diferente do CPF_MELI'
            ELSE 'Valor inválido'
        END AS Comparacao_CPF,
        a.DT_CAPTADA
    FROM product.master_pedido_pessoa.master_pedido AS a
    LEFT JOIN BASE_CPF_MELI AS b
        ON LPAD(a.CPF, 11, '0') = b.CPF_MELI
    WHERE a.MARCA = 'NATURA'
      AND a.CANAL = 'ONLINE'
      AND a.PAIS = 'BRASIL'
      -- AND a.MODELO_COMERCIAL <> 'CB-COMMERCE'
),

BASET AS (
    SELECT *,
           ROW_NUMBER() OVER(PARTITION BY CPF_MASTER ORDER BY DT_CAPTADA DESC) AS ROW_N
    FROM BASE_MASTER
    WHERE CPF_MELI IS NOT NULL
),

BASEMARCACAO AS (
    SELECT
        CPF_MELI,
        MODELO_COMERCIAL,
        Comparacao_CPF
    FROM BASET
    WHERE Comparacao_CPF = 'CPF igual ao CPF_MELI'
      AND ROW_N = 1
    GROUP BY ALL
)

SELECT
    SUBSTR(QUEBRA_DATA_2, 1, 7) AS ANOMES,
    MAR.MODELO_COMERCIAL,
    CASE
        WHEN MAR.Comparacao_CPF = 'CPF igual ao CPF_MELI' THEN 'CPF COMUM'
        ELSE 'EXCLUSIVO MELI'
    END AS Tipo_CPF,
    CASE
        WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 11 THEN 'CPF'
        WHEN LENGTH(TRIM(CAST(CPF AS STRING))) = 14 THEN 'CNPJ'
        ELSE 'Outro'
    END AS Tipo_documento,
    COUNT(DISTINCT CPF) AS CPFS_UNICOS
FROM sandbox.canal_online.tb_mktplace_meli_realizado AS MELI
LEFT JOIN BASEMARCACAO AS MAR
    ON LPAD(MELI.CPF, 11, '0') = MAR.CPF_MELI
WHERE MARCA = 'Natura'
  AND CPF IS NOT NULL
GROUP BY ALL;
